# ============================================================
# SINGLE-QUBIT DEPOLARIZING CHANNEL
# ============================================================

def apply_local_depolarizing(
    rho_state,
    target,
    total_qubits,
    p
):
    """
    Single-qubit depolarizing channel:

        E(rho) =
            (1-p) rho
            + (p/3) [X rho X + Y rho Y + Z rho Z]

    The parameter p is the total probability of a Pauli error.

    For a Pauli observable P = X,Y,Z,

        E^\dagger(P)
            = (1 - 4p/3) P.

    Qubit ordering:

        [ancilla, replica-1, replica-2, ...]

    target=0 is the ancilla.

    The ancilla is NOT depolarized in this experiment.
    """

    I = qt.qeye(2)
    X = qt.sigmax()
    Y = qt.sigmay()
    Z = qt.sigmaz()

    # --------------------------------------------------------
    # Full-system operators
    # --------------------------------------------------------

    I_ops = []
    X_ops = []
    Y_ops = []
    Z_ops = []

    for q in range(total_qubits):

        if q == target:

            I_ops.append(I)
            X_ops.append(X)
            Y_ops.append(Y)
            Z_ops.append(Z)

        else:

            I_ops.append(I)
            X_ops.append(I)
            Y_ops.append(I)
            Z_ops.append(I)

    I_full = qt.tensor(I_ops)
    X_full = qt.tensor(X_ops)
    Y_full = qt.tensor(Y_ops)
    Z_full = qt.tensor(Z_ops)

    # --------------------------------------------------------
    # Depolarizing channel
    # --------------------------------------------------------

    return (
        (1.0 - p)
        * I_full
        * rho_state
        * I_full.dag()

        +

        (p / 3.0)
        * X_full
        * rho_state
        * X_full.dag()

        +

        (p / 3.0)
        * Y_full
        * rho_state
        * Y_full.dag()

        +

        (p / 3.0)
        * Z_full
        * rho_state
        * Z_full.dag()
    )


# ============================================================
# DEPOLARIZING NOISE ON ALL SYSTEM/REPLICA QUBITS
# ============================================================

def apply_system_depolarizing(
    rho_state,
    m,
    n,
    p
):
    """
    Apply independent single-qubit depolarizing noise to
    every system qubit in every replica.

    The ancilla is excluded.

    Total number of qubits:

        1 + m*n

    where qubit 0 is the ancilla.
    """

    total_qubits = 1 + m * n

    # System/replica qubits:
    # targets 1,...,m*n

    for target in range(1, total_qubits):

        rho_state = apply_local_depolarizing(
            rho_state=rho_state,
            target=target,
            total_qubits=total_qubits,
            p=p
        )

    return rho_state


# ============================================================
# R-ZNE FOLDING CALCULATION
# ============================================================

def calculate_rzne_data(
    framework,
    p=0.02,
    max_c=4,
    shots=None
):
    """
    R-ZNE folding under system/replica depolarizing noise.

    Folding:

        U_c = U (U^\dagger U)^c

    with

        s_c = 2c + 1.

    Depolarizing noise is applied after every U and
    U^\dagger block.

    The ancilla is kept noiseless.
    """

    rho = framework.rho
    m = framework.m
    n = framework.n

    U = framework.CVm
    Udag = U.dag()

    # --------------------------------------------------------
    # Initial replicated state
    # --------------------------------------------------------

    rho_total = qt.tensor(
        framework.rho_anc,
        *[rho for _ in range(m)]
    )

    # --------------------------------------------------------
    # Final Hadamard on ancilla
    # --------------------------------------------------------

    Hanc = qt.tensor(
        framework.H,
        *[
            framework.I
            for _ in range(m * n)
        ]
    )

    # --------------------------------------------------------
    # Post-H measurement observable
    #
    # H X H = Z
    #
    # Therefore measuring Z after H is equivalent to measuring
    # X before the final H.
    # --------------------------------------------------------

    Zanc = qt.tensor(
        qt.sigmaz(),
        *[
            framework.I
            for _ in range(m * n)
        ]
    )

    # --------------------------------------------------------
    # Noisy U block
    # --------------------------------------------------------

    def noisy_U(rho_state):

        rho_state = U * rho_state * Udag

        rho_state = apply_system_depolarizing(
            rho_state=rho_state,
            m=m,
            n=n,
            p=p
        )

        return rho_state

    # --------------------------------------------------------
    # Noisy U^\dagger block
    # --------------------------------------------------------

    def noisy_Udag(rho_state):

        rho_state = Udag * rho_state * U

        rho_state = apply_system_depolarizing(
            rho_state=rho_state,
            m=m,
            n=n,
            p=p
        )

        return rho_state

    # --------------------------------------------------------
    # Execute folded circuit
    # --------------------------------------------------------

    def execute_folded_circuit(c):

        rho_state = rho_total.copy()

        # Initial U
        rho_state = noisy_U(rho_state)

        # Additional U^\dagger U pairs
        for _ in range(c):

            rho_state = noisy_Udag(rho_state)
            rho_state = noisy_U(rho_state)

        # Final Hadamard
        rho_state = (
            Hanc
            * rho_state
            * Hanc.dag()
        )

        return rho_state

    # --------------------------------------------------------
    # Exact nonlinear invariant
    # --------------------------------------------------------

    R_exact = np.real(
        (rho ** m).tr()
    )

    # --------------------------------------------------------
    # Storage
    # --------------------------------------------------------

    scales = []
    values = []

    # --------------------------------------------------------
    # Folded simulations
    # --------------------------------------------------------

    for c in range(max_c + 1):

        s = 2 * c + 1

        rho_final = execute_folded_circuit(c)

        expectation = np.real(
            (Zanc * rho_final).tr()
        )

        # ----------------------------------------------------
        # Optional finite-shot sampling
        # ----------------------------------------------------

        if shots is not None:

            p0 = (1.0 + expectation) / 2.0
            p0 = np.clip(p0, 0.0, 1.0)

            samples = np.random.choice(
                [1.0, -1.0],
                size=shots,
                p=[p0, 1.0 - p0]
            )

            value = np.mean(samples)

        else:

            value = expectation

        scales.append(s)
        values.append(value)

    scales = np.asarray(scales, dtype=float)
    values = np.asarray(values, dtype=float)

    # ========================================================
    # LOG-LINEAR FIT
    # ========================================================

    if np.all(values > 0):

        log_values = np.log(values)

        fit = linregress(
            scales,
            log_values
        )

        slope = fit.slope
        intercept = fit.intercept

        alpha_eff = np.exp(slope)
        R_fit = np.exp(intercept)

        R2_fit = fit.rvalue ** 2

        log_fit = (
            intercept
            + slope * scales
        )

    else:

        log_values = np.full_like(
            scales,
            np.nan
        )

        alpha_eff = np.nan
        R_fit = np.nan
        R2_fit = np.nan

        log_fit = np.full_like(
            scales,
            np.nan
        )

    # ========================================================
    # TWO-POINT R-ZNE
    # ========================================================

    R1 = values[0]
    R3 = values[1]

    if R1 > 0 and R3 > 0:

        R_RZNE = np.sqrt(
            R1 ** 3 / R3
        )

    else:

        R_RZNE = np.nan

    # ========================================================
    # ERRORS
    # ========================================================

    raw_error = abs(
        R1 - R_exact
    )

    rzne_error = abs(
        R_RZNE - R_exact
    )

    return {
        "scales": scales,
        "values": values,

        "log_values": log_values,
        "log_fit": log_fit,

        "exact": R_exact,

        "p": p,

        "alpha_eff": alpha_eff,
        "R_fit": R_fit,
        "R2_fit": R2_fit,

        "R1": R1,
        "R3": R3,
        "R_RZNE": R_RZNE,

        "raw_error": raw_error,
        "rzne_error": rzne_error,

        "m": m,
        "n": n,
        "shots": shots
    }


