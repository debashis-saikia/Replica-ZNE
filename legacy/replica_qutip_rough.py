import numpy as np
import qutip as qt
from scipy.stats import linregress


# ============================================================
# GENERAL NOISE CHANNELS
# ============================================================

def apply_dephasing(rho, qubit, n_qubits, p):
    """
    Phase-flip channel:

        E(rho) = (1-p) rho + p Z rho Z

    Acts on one selected qubit.
    """

    ops = [
        qt.qeye(2)
        for _ in range(n_qubits)
    ]

    ops[qubit] = qt.sigmaz()

    Z = qt.tensor(ops)

    return (
        (1 - p) * rho
        + p * Z * rho * Z
    )


def apply_depolarizing(rho, qubit, n_qubits, p):
    """
    Single-qubit depolarizing channel:

        E(rho)
        = (1-p) rho
          + p/3 [X rho X + Y rho Y + Z rho Z]

    For a traceless single-qubit Pauli observable P,

        E^\dagger(P)
        = (1 - 4p/3) P.
    """

    paulis = [
        qt.sigmax(),
        qt.sigmay(),
        qt.sigmaz()
    ]

    result = (1 - p) * rho

    for P in paulis:

        ops = [
            qt.qeye(2)
            for _ in range(n_qubits)
        ]

        ops[qubit] = P

        Pfull = qt.tensor(ops)

        result += (
            p / 3
            * Pfull * rho * Pfull
        )

    return result


def apply_amplitude_damping(rho, qubit, n_qubits, gamma):
    """
    Single-qubit amplitude damping channel.

        E0 = |0><0| + sqrt(1-gamma)|1><1|
        E1 = sqrt(gamma)|0><1|

    """

    E0_single = qt.Qobj(
        [
            [1, 0],
            [0, np.sqrt(1 - gamma)]
        ]
    )

    E1_single = qt.Qobj(
        [
            [0, np.sqrt(gamma)],
            [0, 0]
        ]
    )

    E0_ops = [
        qt.qeye(2)
        for _ in range(n_qubits)
    ]

    E1_ops = [
        qt.qeye(2)
        for _ in range(n_qubits)
    ]

    E0_ops[qubit] = E0_single
    E1_ops[qubit] = E1_single

    E0 = qt.tensor(E0_ops)
    E1 = qt.tensor(E1_ops)

    return (
        E0 * rho * E0.dag()
        +
        E1 * rho * E1.dag()
    )


# ============================================================
# APPLY A SELECTED NOISE CHANNEL TO ALL SYSTEM QUBITS
# ============================================================

def apply_noise_all_system_qubits(
    rho,
    framework,
    noise_type,
    strength
):
    """
    Apply the selected noise channel independently to
    every replica/system qubit.

    The ancilla is NOT directly noised here.

    Qubit ordering:

        0                  -> ancilla
        1 ... m*n          -> replica qubits
    """

    n_total = framework.total_qubits

    rho_noisy = rho

    # Skip qubit 0 because it is the ancilla
    for qubit in range(1, n_total):

        if noise_type == "dephasing":

            rho_noisy = apply_dephasing(
                rho_noisy,
                qubit,
                n_total,
                strength
            )

        elif noise_type == "depolarizing":

            rho_noisy = apply_depolarizing(
                rho_noisy,
                qubit,
                n_total,
                strength
            )

        elif noise_type == "amplitude_damping":

            rho_noisy = apply_amplitude_damping(
                rho_noisy,
                qubit,
                n_total,
                strength
            )

        else:

            raise ValueError(
                f"Unknown noise type: {noise_type}"
            )

    return rho_noisy


