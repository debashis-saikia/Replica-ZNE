def run_rzne_folding_test(
    framework,
    p=0.02,
    max_c=4,
    shots=None
):
    """
    Test Replica Zero-Noise Extrapolation using actual
    unitary folding

        U_c = U (U^\dagger U)^c

    with noise applied after every physical U/U^\dagger block.

    Parameters
    ----------
    framework : ReplicaShadowFramework
        Existing replica-interference framework.

    p : float
        Phase-flip probability.

    max_c : int
        Maximum folding index.
        c = 0,1,...,max_c
        gives noise scales s = 1,3,...,2*max_c+1.

    shots : int or None
        If None, calculate deterministic expectation values.
        Otherwise, sample the ancilla measurement.
    """

    # --------------------------------------------------------
    # Basic quantities
    # --------------------------------------------------------

    rho = framework.rho
    m = framework.m

    U = framework.CVm
    Udag = U.dag()

    n_total = framework.total_qubits

    # Initial replicated state
    rho_total = qt.tensor(
        framework.rho_anc,
        *[rho for _ in range(m)]
    )

    # --------------------------------------------------------
    # Final Hadamard on ancilla
    # --------------------------------------------------------

    Hanc = qt.tensor(
        framework.H,
        *[
            framework.I
            for _ in range(m * framework.n)
        ]
    )

    # --------------------------------------------------------
    # Ancilla measurement operator
    #
    # After final H, measuring computational basis gives
    #
    #       <Z_anc>
    #
    # which equals the replica interference signal.
    # --------------------------------------------------------

    Zanc = qt.tensor(
        qt.sigmaz(),
        *[
            framework.I
            for _ in range(m * framework.n)
        ]
    )

    # --------------------------------------------------------
    # Phase-flip noise on the ancilla
    #
    # N(rho) = (1-p) rho + p Z rho Z
    #
    # In the Heisenberg picture:
    #
    # N^\dagger(X) = (1-2p) X
    #
    # Therefore
    #
    # alpha = 1 - 2p
    # --------------------------------------------------------

    Zfull = Zanc

    def apply_noise(rho_state):
        return (
            (1.0 - p) * rho_state
            + p * Zfull * rho_state * Zfull
        )

    # --------------------------------------------------------
    # One noisy U block
    # --------------------------------------------------------

    def noisy_U(rho_state):

        rho_state = U * rho_state * Udag

        rho_state = apply_noise(rho_state)

        return rho_state

    # --------------------------------------------------------
    # One noisy U^\dagger block
    # --------------------------------------------------------

    def noisy_Udag(rho_state):

        rho_state = Udag * rho_state * U

        rho_state = apply_noise(rho_state)

        return rho_state

    # --------------------------------------------------------
    # Execute folded circuit
    #
    # c = 0:
    #
    #       U
    #
    # c = 1:
    #
    #       U -> U^\dagger -> U
    #
    # c = 2:
    #
    #       U -> U^\dagger -> U
    #         -> U^\dagger -> U
    #
    # Therefore total number of physical blocks is
    #
    #       s = 2c + 1
    # --------------------------------------------------------

    def execute_folded_circuit(c):

        rho_state = rho_total.copy()

        # First U
        rho_state = noisy_U(rho_state)

        # Each additional folding adds U^\dagger U
        for _ in range(c):

            rho_state = noisy_Udag(rho_state)
            rho_state = noisy_U(rho_state)

        # Final H on ancilla
        rho_state = (
            Hanc
            * rho_state
            * Hanc.dag()
        )

        return rho_state

