    # =========================================================
    # DEPOLARIZING CHANNEL
    # =========================================================

    def depolarizing_channel(
        self,
        rho,
        p
    ):
        """
        Single-qubit depolarizing channel:

            E(rho)
            =
            (1-p) rho
            +
            p I/2

        Applied independently to every qubit.
        """

        if p < 0 or p > 1:
            raise ValueError(
                "p must be between 0 and 1."
            )

        D = rho.dims[0]

        n_total = len(D)

        result = rho

        for q in range(n_total):

            # Construct local channel:
            #
            # E_q(rho)
            #
            # = (1-p)rho
            #   + p/2 (I_q rho I_q)

            # Rather than applying the channel through
            # a superoperator, construct the local
            # depolarizing map explicitly.

            ops = []

            for j in range(n_total):

                if j == q:
                    ops.append(self.I)
                else:
                    ops.append(qeye(D[j]))

            I_full = tensor(ops)

            result = (
                (1 - p) * result
                +
                p * (
                    I_full
                    * result
                    * I_full.dag()
                ) / 2
            )

        return result


    # =========================================================
    # DEPHASING CHANNEL
    # =========================================================

    def dephasing_channel(
        self,
        rho,
        p
    ):
        """
        Phase-flip / dephasing channel:

            E(rho)
            =
            (1-p)rho
            +
            p Z rho Z

        Applied independently to every qubit.
        """

        if p < 0 or p > 1:
            raise ValueError(
                "p must be between 0 and 1."
            )

        n_total = len(
            rho.dims[0]
        )

        Z = sigmaz()

        result = rho

        for q in range(n_total):

            ops = []

            for j in range(n_total):

                if j == q:
                    ops.append(Z)
                else:
                    ops.append(
                        qeye(rho.dims[0][j])
                    )

            Z_full = tensor(ops)

            result = (
                (1 - p) * result
                +
                p *
                Z_full
                * result
                * Z_full.dag()
            )

        return result


    # =========================================================
    # AMPLITUDE DAMPING
    # =========================================================

    def amplitude_damping_channel(
        self,
        rho,
        gamma
    ):
        """
        Amplitude damping channel:

            K0 =
                [[1, 0],
                 [0, sqrt(1-gamma)]]

            K1 =
                [[0, sqrt(gamma)],
                 [0, 0]]

        Applied independently to every qubit.
        """

        if gamma < 0 or gamma > 1:
            raise ValueError(
                "gamma must be between 0 and 1."
            )

        K0 = Qobj(
            [
                [1, 0],
                [0, np.sqrt(1 - gamma)]
            ]
        )

        K1 = Qobj(
            [
                [0, np.sqrt(gamma)],
                [0, 0]
            ]
        )

        n_total = len(
            rho.dims[0]
        )

        result = rho

        for q in range(n_total):

            ops0 = []
            ops1 = []

            for j in range(n_total):

                if j == q:

                    ops0.append(K0)
                    ops1.append(K1)

                else:

                    ops0.append(
                        qeye(rho.dims[0][j])
                    )

                    ops1.append(
                        qeye(rho.dims[0][j])
                    )

            K0_full = tensor(ops0)
            K1_full = tensor(ops1)

            result = (
                K0_full
                * result
                * K0_full.dag()
                +
                K1_full
                * result
                * K1_full.dag()
            )

        return result


    # =========================================================
    # GENERIC NOISE APPLICATION
    # =========================================================

    def apply_noise(
        self,
        rho,
        noise_type=None,
        noise_strength=0.0
    ):

        if noise_type is None:
            return rho

        if noise_type == "depolarizing":

            return self.depolarizing_channel(
                rho,
                noise_strength
            )

        elif noise_type == "dephasing":

            return self.dephasing_channel(
                rho,
                noise_strength
            )

        elif noise_type == "amplitude_damping":

            return self.amplitude_damping_channel(
                rho,
                noise_strength
            )

        else:

            raise ValueError(
                "Unknown noise type. "
                "Use 'depolarizing', "
                "'dephasing', or "
                "'amplitude_damping'."
            )


    # =========================================================
    # NOISY SINGLE SHOT
    # =========================================================

    def generate_noisy_snapshot(
        self,
        noise_type=None,
        noise_strength=0.0
    ):

        # -----------------------------------------------------
        # Initial state
        # -----------------------------------------------------

        rho_total = (
            self.replica_state()
        )

        # -----------------------------------------------------
        # Apply noise BEFORE controlled permutation
        #
        # This is one concrete noise model.
        # We will later distinguish this from
        # gate-local noise.
        # -----------------------------------------------------

        rho_total = self.apply_noise(
            rho_total,
            noise_type,
            noise_strength
        )

        # -----------------------------------------------------
        # Controlled permutation
        # -----------------------------------------------------

        rho_after = (
            self.CVm
            * rho_total
            * self.CVm.dag()
        )

        # -----------------------------------------------------
        # Apply noise AFTER controlled permutation
        #
        # This lets us model circuit noise surrounding
        # the interference block.
        # -----------------------------------------------------

        rho_after = self.apply_noise(
            rho_after,
            noise_type,
            noise_strength
        )

        # -----------------------------------------------------
        # Final ancilla Hadamard
        # -----------------------------------------------------

        rho_after = (
            self.apply_final_hadamard(
                rho_after
            )
        )

        # -----------------------------------------------------
        # Optional final noise
        # -----------------------------------------------------

        rho_after = self.apply_noise(
            rho_after,
            noise_type,
            noise_strength
        )

        # -----------------------------------------------------
        # Ancilla probabilities
        # -----------------------------------------------------

        p0, p1 = (
            self.ancilla_probabilities(
                rho_after
            )
        )

        p0 = max(0.0, p0)
        p1 = max(0.0, p1)

        norm = p0 + p1

        p0 /= norm
        p1 /= norm

        outcome = np.random.choice(
            [0, 1],
            p=[p0, p1]
        )

        return (-1) ** outcome


    # =========================================================
    # NOISY ESTIMATE
    # =========================================================

    def estimate_noisy_trace_power(
        self,
        noise_type=None,
        noise_strength=0.0,
        shots=None
    ):

        if shots is None:
            shots = self.shots

        samples = np.array([
            self.generate_noisy_snapshot(
                noise_type=noise_type,
                noise_strength=noise_strength
            )
            for _ in range(shots)
        ])

        return np.mean(samples)


    # =========================================================
    # =========================================================
    # UNITARY FOLDING
    # =========================================================
    # =========================================================


    def folded_permutation(
        self,
        c
    ):
        """
        Construct

            U_m^(c)
            =
            U_m (U_m^dagger U_m)^c

        where

            U_m = C(V_m).

        c=0:
            U

        c=1:
            U U^dagger U

        c=2:
            U U^dagger U U^dagger U
        """

        U = self.CVm

        folded = U

        for _ in range(c):

            folded = (
                folded
                *
                U.dag()
                *
                U
            )

        return folded


    # =========================================================
    # FOLDED NOISY SNAPSHOT
    # =========================================================

    def generate_folded_snapshot(
        self,
        c=0,
        noise_type=None,
        noise_strength=0.0
    ):

        # -----------------------------------------------------
        # Initial replicated state
        # -----------------------------------------------------

        rho_total = (
            self.replica_state()
        )

        # -----------------------------------------------------
        # Prepare folded permutation
        # -----------------------------------------------------

        U_folded = (
            self.folded_permutation(c)
        )

        # -----------------------------------------------------
        # Apply folded circuit
        # -----------------------------------------------------

        rho_after = (
            U_folded
            * rho_total
            * U_folded.dag()
        )

        # -----------------------------------------------------
        # Apply effective circuit noise
        #
        # We apply the noise channel once per circuit block.
        #
        # This is a simplified effective noise model and
        # will allow us to test the R-ZNE scaling hypothesis.
        # -----------------------------------------------------

        number_of_blocks = (
            2 * c + 1
        )

        for _ in range(
            number_of_blocks
        ):

            rho_after = self.apply_noise(
                rho_after,
                noise_type,
                noise_strength
            )

        # -----------------------------------------------------
        # Final ancilla H
        # -----------------------------------------------------

        rho_after = (
            self.apply_final_hadamard(
                rho_after
            )
        )

        # -----------------------------------------------------
        # Measurement
        # -----------------------------------------------------

        p0, p1 = (
            self.ancilla_probabilities(
                rho_after
            )
        )

        p0 = max(0.0, p0)
        p1 = max(0.0, p1)

        norm = p0 + p1

        p0 /= norm
        p1 /= norm

        outcome = np.random.choice(
            [0, 1],
            p=[p0, p1]
        )

        return (-1) ** outcome


    # =========================================================
    # FOLDED ESTIMATE
    # =========================================================

    def estimate_folded(
        self,
        c,
        noise_type=None,
        noise_strength=0.0,
        shots=None
    ):

        if shots is None:
            shots = self.shots

        samples = np.array([
            self.generate_folded_snapshot(
                c=c,
                noise_type=noise_type,
                noise_strength=noise_strength
            )
            for _ in range(shots)
        ])

        return np.mean(samples)


    # =========================================================
    # =========================================================
    # R-ZNE
    # =========================================================
    # =========================================================


    def RZNE(
        self,
        noise_type,
        noise_strength,
        shots=None
    ):
        """
        Two-point Replica Zero-Noise Extrapolation.

        Uses

            R(0) = alpha R

            R(1) = alpha^3 R

        and therefore

            R_RZNE
            =
            sqrt[R(0)^3 / R(1)].
        """

        if shots is None:
            shots = self.shots

        # -----------------------------------------------------
        # Noise scale 1
        # -----------------------------------------------------

        R0 = self.estimate_folded(
            c=0,
            noise_type=noise_type,
            noise_strength=noise_strength,
            shots=shots
        )

        # -----------------------------------------------------
        # Noise scale 3
        # -----------------------------------------------------

        R1 = self.estimate_folded(
            c=1,
            noise_type=noise_type,
            noise_strength=noise_strength,
            shots=shots
        )

        # -----------------------------------------------------
        # R-ZNE
        # -----------------------------------------------------

        if R1 <= 0:

            R_rzne = np.nan

        else:

            R_rzne = np.sqrt(
                R0**3 / R1
            )

        # -----------------------------------------------------
        # Standard Richardson
        # -----------------------------------------------------

        R_richardson = (
            3 * R0 - R1
        ) / 2

        return {
            "R0": R0,
            "R1": R1,
            "R_RZNE": R_rzne,
            "R_Richardson": R_richardson
        }


    # =========================================================
    # RENYI ENTROPY
    # =========================================================

    def renyi_entropy(
        self,
        trm
    ):

        if trm <= 0:
            return np.inf

        return (
            1 / (1 - self.m)
        ) * np.log(trm)

