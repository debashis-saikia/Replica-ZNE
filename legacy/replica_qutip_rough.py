# ------------------------------------------------------------
# 1. Basic deterministic ancilla expectation
# ------------------------------------------------------------

def ancilla_Z_expectation(rho_total, total_qubits):
    """
    Expectation value of Z on the ancilla.

    Qubit ordering:
        ancilla + replica system
    """

    Z = qt.sigmaz()

    Z_anc = qt.tensor(
        Z,
        *[qt.qeye(2) for _ in range(total_qubits - 1)]
    )

    return float(np.real(qt.expect(Z_anc, rho_total)))


# ------------------------------------------------------------
# 2. Local Pauli-Z channel
# ------------------------------------------------------------

def apply_pauli_z_noise(rho, qubit, total_qubits, p):
    """
    Apply a local Pauli-Z channel

        E(rho) = (1-p) rho + p Z rho Z

    on the specified qubit.
    """

    operators = [
        qt.qeye(2)
        for _ in range(total_qubits)
    ]

    operators[qubit] = qt.sigmaz()

    Z_full = qt.tensor(operators)

    return (
        (1 - p) * rho
        +
        p * Z_full * rho * Z_full
    )


# ------------------------------------------------------------
# 3. Apply local noise to ALL replica qubits
# ------------------------------------------------------------

def apply_replica_Z_noise(
    rho,
    framework,
    p
):

    result = rho

    # qubit 0 = ancilla
    # replica qubits = 1,...,m*n

    for q in range(
        1,
        framework.total_qubits
    ):

        result = apply_pauli_z_noise(
            result,
            q,
            framework.total_qubits,
            p
        )

    return result


# ------------------------------------------------------------
# 4. Build initial replica state
# ------------------------------------------------------------

def deterministic_initial_state(framework):

    rho_rep = qt.tensor(
        *[
            framework.rho
            for _ in range(framework.m)
        ]
    )

    return qt.tensor(
        framework.rho_anc,
        rho_rep
    )


# ------------------------------------------------------------
# 5. One noisy replica block
# ------------------------------------------------------------

def noisy_replica_block(
    framework,
    rho,
    p
):

    # Ideal controlled permutation
    rho_after_CVm = (
        framework.CVm
        * rho
        * framework.CVm.dag()
    )

    # Apply local Pauli-Z noise
    rho_after_noise = apply_replica_Z_noise(
        rho_after_CVm,
        framework,
        p
    )

    return rho_after_noise


# ------------------------------------------------------------
# 6. Final Hadamard
# ------------------------------------------------------------

def apply_final_H(
    framework,
    rho
):

    H_full = qt.tensor(
        framework.H,
        *[
            qt.qeye(2)
            for _ in range(framework.total_qubits - 1)
        ]
    )

    return (
        H_full
        * rho
        * H_full.dag()
    )


