# ============================================================
# SINGLE-QUBIT DEPHASING
# ============================================================

def apply_local_dephasing(
    rho_state,
    target,
    total_qubits,
    p
):
    """
    Apply a single-qubit Z-dephasing channel to `target`.

        E(rho) = (1-p) rho + p Z rho Z

    The target qubit is specified in the ordering

        [ancilla, replica-1, replica-2, ...]

    Hence target=0 is the ancilla.

    The ancilla will NOT be dephased in this experiment.
    """

    Z = qt.sigmaz()

    operators_I = []
    operators_Z = []

    for q in range(total_qubits):

        if q == target:
            operators_I.append(qt.qeye(2))
            operators_Z.append(Z)

        else:
            operators_I.append(qt.qeye(2))
            operators_Z.append(qt.qeye(2))

    I_full = qt.tensor(operators_I)
    Z_full = qt.tensor(operators_Z)

    return (
        (1.0 - p) * I_full * rho_state * I_full.dag()
        +
        p * Z_full * rho_state * Z_full.dag()
    )


# ============================================================
# DEPHASING ON ALL REPLICA/SYSTEM QUBITS
# ============================================================

def apply_system_dephasing(
    rho_state,
    m,
    n,
    p
):
    """
    Apply independent Z-dephasing to every system qubit
    in every replica.

    The ancilla is excluded.

    Total qubits:

        1 + m*n

    with qubit 0 = ancilla.
    """

    total_qubits = 1 + m * n

    # System qubits are targets 1,...,m*n
    for target in range(1, total_qubits):

        rho_state = apply_local_dephasing(
            rho_state=rho_state,
            target=target,
            total_qubits=total_qubits,
            p=p
        )

    return rho_state


# ============================================================
# R-ZNE FOLDING CALCULATION
# ============================================================

def calculate_rzne_data(
    framework,
    p=0.02,
    max_c=4,
    shots=None
):
    """
    R-ZNE folding under system/replica Z-dephasing.

    Folding:

        U_c = U (U^\dagger U)^c

    with

        s_c = 2c + 1.

    Dephasing is applied after every U and U^\dagger block.

    The ancilla is kept noiseless.
    """

    rho = framework.rho
    m = framework.m
    n = framework.n

    U = framework.CVm
    Udag = U.dag()

    # --------------------------------------------------------
    # Initial replicated state
    # --------------------------------------------------------

    rho_total = qt.tensor(
        framework.rho_anc,
        *[rho for _ in range(m)]
    )

    # --------------------------------------------------------
    # Final Hadamard
    # --------------------------------------------------------

    Hanc = qt.tensor(
        framework.H,
        *[
            framework.I
            for _ in range(m * n)
        ]
    )

    # --------------------------------------------------------
    # Post-H measurement
    #
    # H X H = Z
    #
    # Therefore measuring Z after the final H is equivalent
    # to measuring the pre-H ancilla X observable.
    # --------------------------------------------------------

    Zanc = qt.tensor(
        qt.sigmaz(),
        *[
            framework.I
            for _ in range(m * n)
        ]
    )

    # --------------------------------------------------------
    # Noisy U block
    # --------------------------------------------------------

    def noisy_U(rho_state):

        rho_state = U * rho_state * Udag

        rho_state = apply_system_dephasing(
            rho_state=rho_state,
            m=m,
            n=n,
            p=p
        )

        return rho_state

    # --------------------------------------------------------
    # Noisy U^\dagger block
    # --------------------------------------------------------

    def noisy_Udag(rho_state):

        rho_state = Udag * rho_state * U

        rho_state = apply_system_dephasing(
            rho_state=rho_state,
            m=m,
            n=n,
            p=p
        )

        return rho_state

    # --------------------------------------------------------
    # Execute folded circuit
    # --------------------------------------------------------

    def execute_folded_circuit(c):

        rho_state = rho_total.copy()

        # Initial U
        rho_state = noisy_U(rho_state)

        # Additional U^\dagger U pairs
        for _ in range(c):

            rho_state = noisy_Udag(rho_state)
            rho_state = noisy_U(rho_state)

        # Final Hadamard
        rho_state = (
            Hanc
            * rho_state
            * Hanc.dag()
        )

        return rho_state

    # --------------------------------------------------------
    # Exact nonlinear invariant
    # --------------------------------------------------------

    R_exact = np.real(
        (rho ** m).tr()
    )

    # --------------------------------------------------------
    # Storage
    # --------------------------------------------------------

    scales = []
    values = []

    # --------------------------------------------------------
    # Folded simulations
    # --------------------------------------------------------

    for c in range(max_c + 1):

        s = 2 * c + 1

        rho_final = execute_folded_circuit(c)

        expectation = np.real(
            (Zanc * rho_final).tr()
        )

        # ----------------------------------------------------
        # Optional finite-shot sampling
        # ----------------------------------------------------

        if shots is not None:

            p0 = (1.0 + expectation) / 2.0
            p0 = np.clip(p0, 0.0, 1.0)

            samples = np.random.choice(
                [1.0, -1.0],
                size=shots,
                p=[p0, 1.0 - p0]
            )

            value = np.mean(samples)

        else:

            value = expectation

        scales.append(s)
        values.append(value)

    scales = np.asarray(scales, dtype=float)
    values = np.asarray(values, dtype=float)

    # ========================================================
    # LOG-LINEAR FIT
    # ========================================================

    if np.all(values > 0):

        log_values = np.log(values)

        fit = linregress(
            scales,
            log_values
        )

        slope = fit.slope
        intercept = fit.intercept

        alpha_eff = np.exp(slope)
        R_fit = np.exp(intercept)

        R2_fit = fit.rvalue ** 2

        log_fit = (
            intercept
            + slope * scales
        )

    else:

        log_values = np.full_like(
            scales,
            np.nan
        )

        alpha_eff = np.nan
        R_fit = np.nan
        R2_fit = np.nan

        log_fit = np.full_like(
            scales,
            np.nan
        )

    # ========================================================
    # TWO-POINT R-ZNE
    #
    # If:
    #
    #     R(s) = R alpha^s
    #
    # then:
    #
    #     R = sqrt[R(1)^3/R(3)]
    #
    # We do NOT assume this is exact for system dephasing.
    # ========================================================

    R1 = values[0]
    R3 = values[1]

    if R1 > 0 and R3 > 0:

        R_RZNE = np.sqrt(
            R1 ** 3 / R3
        )

    else:

        R_RZNE = np.nan

    # ========================================================
    # ERRORS
    # ========================================================

    raw_error = abs(
        R1 - R_exact
    )

    rzne_error = abs(
        R_RZNE - R_exact
    )

    return {
        "scales": scales,
        "values": values,

        "log_values": log_values,
        "log_fit": log_fit,

        "exact": R_exact,

        "p": p,

        "alpha_eff": alpha_eff,
        "R_fit": R_fit,
        "R2_fit": R2_fit,

        "R1": R1,
        "R3": R3,
        "R_RZNE": R_RZNE,

        "raw_error": raw_error,
        "rzne_error": rzne_error,

        "m": m,
        "n": n,
        "shots": shots
    }


