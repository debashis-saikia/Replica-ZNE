# LINEAR FIT FUNCTION
# ============================================================

def linear_fit_and_R2(x, y):

    mask = np.isfinite(y)

    x_fit = x[mask]
    y_fit = y[mask]

    coefficients = np.polyfit(
        x_fit,
        y_fit,
        1
    )

    slope = coefficients[0]
    intercept = coefficients[1]

    y_pred = (
        slope * x_fit
        +
        intercept
    )

    SS_res = np.sum(
        (y_fit - y_pred)**2
    )

    SS_tot = np.sum(
        (y_fit - np.mean(y_fit))**2
    )

    if SS_tot > 0:
        R2 = 1 - SS_res / SS_tot
    else:
        R2 = np.nan

    return (
        slope,
        intercept,
        R2
    )


