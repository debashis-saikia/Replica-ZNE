# R-ZNE FOLDING CALCULATION
# ============================================================

def calculate_rzne_data(
    framework,
    p=0.02,
    max_c=4,
    shots=None
):
    """
    Run the actual unitary-folding R-ZNE experiment.

    Folding:
        U_c = U (U^\dagger U)^c

    Therefore:
        s = 2c + 1

    Returns all numerical quantities needed for plotting.
    """

    rho = framework.rho
    m = framework.m

    U = framework.CVm
    Udag = U.dag()

    # --------------------------------------------------------
    # Initial replicated state
    # --------------------------------------------------------

    rho_total = qt.tensor(
        framework.rho_anc,
        *[rho for _ in range(m)]
    )

    # --------------------------------------------------------
    # Final Hadamard
    # --------------------------------------------------------

    Hanc = qt.tensor(
        framework.H,
        *[
            framework.I
            for _ in range(m * framework.n)
        ]
    )

    # --------------------------------------------------------
    # Ancilla Z observable
    #
    # After final H:
    #
    #     <Z_A> = replica interference signal
    #
    # --------------------------------------------------------

    Zanc = qt.tensor(
        qt.sigmaz(),
        *[
            framework.I
            for _ in range(m * framework.n)
        ]
    )

    # --------------------------------------------------------
    # Ancilla phase-flip noise
    #
    # N(rho) = (1-p) rho + p Z rho Z
    #
    # N^\dagger(X) = (1-2p) X
    #
    # alpha = 1 - 2p
    # --------------------------------------------------------

    Zfull = Zanc

    def apply_noise(rho_state):

        return (
            (1.0 - p) * rho_state
            + p * Zfull * rho_state * Zfull
        )

    # --------------------------------------------------------
    # Noisy U block
    # --------------------------------------------------------

    def noisy_U(rho_state):

        rho_state = U * rho_state * Udag
        rho_state = apply_noise(rho_state)

        return rho_state

    # --------------------------------------------------------
    # Noisy U^\dagger block
    # --------------------------------------------------------

    def noisy_Udag(rho_state):

        rho_state = Udag * rho_state * U
        rho_state = apply_noise(rho_state)

        return rho_state

    # --------------------------------------------------------
    # Execute folded circuit
    # --------------------------------------------------------

    def execute_folded_circuit(c):

        rho_state = rho_total.copy()

        # First U
        rho_state = noisy_U(rho_state)

        # Additional U^\dagger U pairs
        for _ in range(c):

            rho_state = noisy_Udag(rho_state)
            rho_state = noisy_U(rho_state)

        # Final H
        rho_state = (
            Hanc
            * rho_state
            * Hanc.dag()
        )

        return rho_state

    # --------------------------------------------------------
    # Exact nonlinear invariant
    # --------------------------------------------------------

    R_exact = np.real((rho ** m).tr())

    # --------------------------------------------------------
    # Theoretical eigenvalue
    # --------------------------------------------------------

    alpha_theory = 1.0 - 2.0 * p

    # --------------------------------------------------------
    # Storage
    # --------------------------------------------------------

    scales = []
    values = []
    predictions = []

    # --------------------------------------------------------
    # Run folded circuits
    # --------------------------------------------------------

    for c in range(max_c + 1):

        s = 2 * c + 1

        rho_final = execute_folded_circuit(c)

        expectation = np.real(
            (Zanc * rho_final).tr()
        )

        # ----------------------------------------------------
        # Optional finite-shot sampling
        # ----------------------------------------------------

        if shots is not None:

            p0 = (1.0 + expectation) / 2.0
            p0 = np.clip(p0, 0.0, 1.0)

            samples = np.random.choice(
                [1.0, -1.0],
                size=shots,
                p=[p0, 1.0 - p0]
            )

            value = np.mean(samples)

        else:

            value = expectation

        prediction = (
            R_exact
            * alpha_theory ** s
        )

        scales.append(s)
        values.append(value)
        predictions.append(prediction)

    scales = np.asarray(scales, dtype=float)
    values = np.asarray(values, dtype=float)
    predictions = np.asarray(predictions, dtype=float)

    # ========================================================
    # LOG-LINEAR FIT
    # ========================================================

    if np.all(values > 0):

        log_values = np.log(values)

        fit = linregress(
            scales,
            log_values
        )

        slope = fit.slope
        intercept = fit.intercept

        alpha_eff = np.exp(slope)
        R_fit = np.exp(intercept)
        R2_fit = fit.rvalue ** 2

        log_fit = (
            intercept
            + slope * scales
        )

    else:

        slope = np.nan
        intercept = np.nan
        alpha_eff = np.nan
        R_fit = np.nan
        R2_fit = np.nan
        log_fit = np.full_like(scales, np.nan)

    # ========================================================
    # TWO-POINT R-ZNE
    #
    # R(1) = R alpha
    # R(3) = R alpha^3
    #
    # R = sqrt[R(1)^3 / R(3)]
    # ========================================================

    R1 = values[0]
    R3 = values[1]

    if R1 > 0 and R3 > 0:

        R_RZNE = np.sqrt(
            R1 ** 3 / R3
        )

    else:

        R_RZNE = np.nan

    # ========================================================
    # ERRORS
    # ========================================================

    raw_error = abs(R1 - R_exact)

    rzne_error = abs(
        R_RZNE - R_exact
    )

    return {
        "scales": scales,
        "values": values,
        "predictions": predictions,
        "log_values": np.log(values)
            if np.all(values > 0)
            else np.full_like(values, np.nan),
        "log_fit": log_fit,

        "exact": R_exact,

        "alpha_theory": alpha_theory,
        "alpha_eff": alpha_eff,

        "R_fit": R_fit,
        "R2_fit": R2_fit,

        "R1": R1,
        "R3": R3,
        "R_RZNE": R_RZNE,

        "raw_error": raw_error,
        "rzne_error": rzne_error,

        "p": p,
        "m": m,
        "shots": shots
    }


