# 5. Noise models
# ============================================================

def build_noise_model(
    kind: str,
    p1: float = 0.0,
    p2: float = 0.0,
    p_readout: float = 0.0,
) -> NoiseModel:

    """
    Build a Qiskit Aer gate-level noise model.

    kind:

        "none"
        "depolarizing"
        "dephasing"
        "amplitude_damping"
    """

    kind = kind.lower()

    noise_model = NoiseModel()

    if kind == "none":
        return noise_model

    if not (0.0 <= p1 <= 1.0):
        raise ValueError("p1 must lie in [0,1].")

    if not (0.0 <= p2 <= 1.0):
        raise ValueError("p2 must lie in [0,1].")

    # Gates used after transpilation
    one_qubit_gates = [
        "rz",
        "sx",
        "x",
        "h",
    ]

    two_qubit_gates = [
        "cx",
    ]

    # --------------------------------------------------------
    # Depolarizing
    # --------------------------------------------------------

    if kind == "depolarizing":

        error_1 = depolarizing_error(
            p1,
            1
        )

        error_2 = depolarizing_error(
            p2,
            2
        )

    # --------------------------------------------------------
    # Phase damping / dephasing
    # --------------------------------------------------------

    elif kind == "dephasing":

        error_1 = phase_damping_error(
            p1
        )

        error_2 = (
            phase_damping_error(p2)
            .tensor(
                phase_damping_error(p2)
            )
        )

    # --------------------------------------------------------
    # Amplitude damping
    # --------------------------------------------------------

    elif kind == "amplitude_damping":

        error_1 = amplitude_damping_error(
            p1
        )

        error_2 = (
            amplitude_damping_error(p2)
            .tensor(
                amplitude_damping_error(p2)
            )
        )

    else:

        raise ValueError(
            "Unknown noise type.\n"
            "Use: none, depolarizing, dephasing, "
            "amplitude_damping"
        )

    # Add one-qubit errors
    noise_model.add_all_qubit_quantum_error(
        error_1,
        one_qubit_gates
    )

    # Add two-qubit errors
    noise_model.add_all_qubit_quantum_error(
        error_2,
        two_qubit_gates
    )

    # --------------------------------------------------------
    # Optional readout error
    # --------------------------------------------------------

    if p_readout > 0:

        readout_error = ReadoutError(
            [
                [1 - p_readout, p_readout],
                [p_readout, 1 - p_readout],
            ]
        )

        noise_model.add_all_qubit_readout_error(
            readout_error
        )

    return noise_model


# ============================================================
# 6. Measurement result
# ============================================================

@dataclass
class MeasurementResult:

    counts: Dict[str, int]

    expectation: float

    shots: int


# ============================================================
# 7. Run circuit
# ============================================================

def simulate_Rm(
    rho: np.ndarray,
    m: int,
    shots: int,
    folding_c: int = 0,
    noise_model: Optional[NoiseModel] = None,
    seed: Optional[int] = 1234,
) -> MeasurementResult:

    """
    Run the replica-interference circuit and estimate

        R_m = <Z_anc>.
    """

    if shots < 1:
        raise ValueError(
            "shots must be >= 1."
        )

    circuit = build_interference_circuit(
        rho=rho,
        m=m,
        folding_c=folding_c,
    )

    backend = AerSimulator(
        method="density_matrix",
        noise_model=noise_model,
    )

    # --------------------------------------------------------
    # Transpile into elementary gates
    # --------------------------------------------------------

    transpiled_circuit = transpile(
        circuit,
        backend=backend,
        optimization_level=0,
    )

    # --------------------------------------------------------
    # Run
    # --------------------------------------------------------

    result = backend.run(
        transpiled_circuit,
        shots=shots,
        seed_simulator=seed,
    ).result()

    raw_counts = result.get_counts()

    counts = {
        "0": 0,
        "1": 0,
    }

    for key, value in raw_counts.items():

        key = str(key).replace(
            " ",
            ""
        )

        bit = key[-1]

        counts[bit] += value

    # c=0 -> +1
    # c=1 -> -1

    expectation = (
        counts["0"] - counts["1"]
    ) / shots

    return MeasurementResult(
        counts=counts,
        expectation=expectation,
        shots=shots,
    )


# ============================================================
# 8. Replica ZNE
# ============================================================

def rz_ne_two_point(
    R0: float,
    R1: float,
) -> float:

    """
    Two-point R-ZNE estimator:

        R = sqrt(R0^3 / R1)

    where

        R0 = R_m(c=0)
        R1 = R_m(c=1)
    """

    if R0 < 0:
        return np.nan

    if R1 <= 0:
        return np.nan

    return np.sqrt(
        (R0**3) / R1
    )


# ============================================================
# 9. Standard Richardson ZNE
# ============================================================

def richardson_two_point(
    R0: float,
    R1: float,
) -> float:

    """
    First-order Richardson extrapolation for noise scales

        s=1 and s=3

    assuming

        R(s) = R + a*s*epsilon + ...
    """

    return (
        3.0 * R0 - R1
    ) / 2.0


# ============================================================
# 10. Complete R-ZNE experiment
# ============================================================

def run_rzne_experiment(
    rho: np.ndarray,
    m: int,
    shots: int,
    noise_model: Optional[NoiseModel],
    seed: int = 1234,
):

    # --------------------------------------------------------
    # Unfolded circuit
    #
    # c=0
    #
    # scale = 1
    # --------------------------------------------------------

    result_0 = simulate_Rm(
        rho=rho,
        m=m,
        shots=shots,
        folding_c=0,
        noise_model=noise_model,
        seed=seed,
    )

    # --------------------------------------------------------
    # One folding layer
    #
    # c=1
    #
    # U U^dagger U
    #
    # scale = 3
    # --------------------------------------------------------

    result_1 = simulate_Rm(
        rho=rho,
        m=m,
        shots=shots,
        folding_c=1,
        noise_model=noise_model,
        seed=seed + 1,
    )

    R0 = result_0.expectation
    R1 = result_1.expectation

    # R-ZNE
    R_RZNE = rz_ne_two_point(
        R0,
        R1
    )

    # Standard Richardson
    R_Richardson = richardson_two_point(
        R0,
        R1
    )

    return {
        "R0": R0,
        "R1": R1,
        "R_RZNE": R_RZNE,
        "R_Richardson": R_Richardson,
        "counts_R0": result_0.counts,
        "counts_R1": result_1.counts,
    }


