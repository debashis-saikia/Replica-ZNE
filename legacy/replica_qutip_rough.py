import numpy as np
from qutip import *
import matplotlib.pyplot as plt


class ReplicaFramework:

    """
    Replica Interference Framework

    Estimates

        R_m(rho) = Tr(rho^m)

    using

        - m identical replicas
        - ancilla-controlled cyclic permutation
        - ancilla interference measurement

    Additional functionality:

        - depolarizing noise
        - dephasing noise
        - amplitude damping
        - unitary folding
        - Replica Zero-Noise Extrapolation (R-ZNE)

    No density-matrix reconstruction is performed.
    """

    # =========================================================
    # INITIALIZATION
    # =========================================================

    def __init__(self, rho, m=2, shots=1000):

        self.rho = rho
        self.m = m
        self.shots = shots

        # Number of qubits in one replica
        self.n = len(rho.dims[0])

        # Total number of qubits
        #
        # 1 ancilla + m replicas
        #
        self.total_qubits = 1 + self.m * self.n

        # -----------------------------------------------------
        # Basic operators
        # -----------------------------------------------------

        self.I = qeye(2)

        self.zero = basis(2, 0)
        self.one = basis(2, 1)

        self.plus = (
            self.zero + self.one
        ).unit()

        self.rho_anc = ket2dm(self.plus)

        # Hadamard
        self.H = Qobj(
            (1 / np.sqrt(2)) *
            np.array([
                [1, 1],
                [1, -1]
            ], dtype=complex),
            dims=[[2], [2]]
        )

        # -----------------------------------------------------
        # Replica permutation
        # -----------------------------------------------------

        self.Vm = self.build_cyclic_permutation()

        self.CVm = self.build_controlled_permutation()


    # =========================================================
    # CYCLIC PERMUTATION
    # =========================================================

    def build_cyclic_permutation(self):

        dim = 2 ** self.total_qubits

        Vm_matrix = np.zeros(
            (dim, dim),
            dtype=complex
        )

        for idx in range(dim):

            bits = list(
                format(
                    idx,
                    f'0{self.total_qubits}b'
                )
            )

            # -------------------------------------------------
            # Extract replicas
            # -------------------------------------------------

            copies = []

            for r in range(self.m):

                start = 1 + r * self.n
                end = start + self.n

                copies.append(
                    bits[start:end]
                )

            # -------------------------------------------------
            # Cyclic permutation
            #
            # (1,2,...,m)
            #
            # ->
            #
            # (m,1,2,...,m-1)
            # -------------------------------------------------

            permuted_copies = (
                [copies[-1]]
                + copies[:-1]
            )

            permuted_bits = []

            for c in permuted_copies:
                permuted_bits.extend(c)

            # Preserve ancilla
            new_bits = (
                [bits[0]]
                + permuted_bits
            )

            new_index = int(
                ''.join(new_bits),
                2
            )

            Vm_matrix[
                new_index,
                idx
            ] = 1

        return Qobj(
            Vm_matrix,
            dims=[
                [2] * self.total_qubits,
                [2] * self.total_qubits
            ]
        )


    # =========================================================
    # CONTROLLED PERMUTATION
    # =========================================================

    def build_controlled_permutation(self):

        proj0 = ket2dm(self.zero)
        proj1 = ket2dm(self.one)

        identity_system = tensor(
            *[
                self.I
                for _ in range(
                    self.m * self.n
                )
            ]
        )

        P0_full = tensor(
            proj0,
            identity_system
        )

        P1_full = tensor(
            proj1,
            identity_system
        )

        return (
            P0_full
            +
            P1_full * self.Vm
        )


    # =========================================================
    # REPLICA STATE
    # =========================================================

    def replica_state(self):

        rho_copies = [
            self.rho
            for _ in range(self.m)
        ]

        return tensor(
            self.rho_anc,
            *rho_copies
        )


    # =========================================================
    # IDEAL REPLICA CIRCUIT
    # =========================================================

    def ideal_state_after_permutation(self):

        rho_total = self.replica_state()

        rho_after = (
            self.CVm
            * rho_total
            * self.CVm.dag()
        )

        return rho_after


    # =========================================================
    # FINAL ANCILLA HADAMARD
    # =========================================================

    def apply_final_hadamard(self, rho):

        Hanc = tensor(
            self.H,
            *[
                self.I
                for _ in range(
                    self.m * self.n
                )
            ]
        )

        return (
            Hanc
            * rho
            * Hanc.dag()
        )


    # =========================================================
    # ANCILLA PROBABILITIES
    # =========================================================

    def ancilla_probabilities(self, rho):

        P0 = tensor(
            ket2dm(self.zero),
            *[
                self.I
                for _ in range(
                    self.m * self.n
                )
            ]
        )

        P1 = tensor(
            ket2dm(self.one),
            *[
                self.I
                for _ in range(
                    self.m * self.n
                )
            ]
        )

        p0 = np.real(
            (P0 * rho).tr()
        )

        p1 = np.real(
            (P1 * rho).tr()
        )

        return p0, p1


    # =========================================================
    # SINGLE IDEAL SHOT
    # =========================================================

    def generate_snapshot(self):

        rho_after = (
            self.ideal_state_after_permutation()
        )

        rho_after = (
            self.apply_final_hadamard(
                rho_after
            )
        )

        p0, p1 = (
            self.ancilla_probabilities(
                rho_after
            )
        )

        # Numerical cleanup
        p0 = max(0.0, p0)
        p1 = max(0.0, p1)

        norm = p0 + p1

        p0 /= norm
        p1 /= norm

        outcome = np.random.choice(
            [0, 1],
            p=[p0, p1]
        )

        # X_k = (-1)^c_k
        return (-1) ** outcome


    # =========================================================
    # IDEAL DATASET
    # =========================================================

    def generate_dataset(self):

        return np.array([
            self.generate_snapshot()
            for _ in range(self.shots)
        ])


    # =========================================================
    # IDEAL ESTIMATE
    # =========================================================

    def estimate_trace_power(self):

        samples = (
            self.generate_dataset()
        )

        return np.mean(samples)


    # =========================================================
    # EXACT TRACE POWER
    # =========================================================

    def exact_trace_power(self):

        return np.real(
            np.trace(
                np.linalg.matrix_power(
                    self.rho.full(),
                    self.m
                )
            )
        )


