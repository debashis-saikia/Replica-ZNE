# ============================================================
# SINGLE-QUBIT AMPLITUDE-DAMPING KRAUS OPERATORS
# ============================================================

def amplitude_damping_kraus(gamma):
    """
    Single-qubit amplitude-damping channel.

    K0 = |0><0| + sqrt(1-gamma)|1><1|
    K1 = sqrt(gamma)|0><1|

    E(rho) = K0 rho K0^\dagger + K1 rho K1^\dagger
    """

    K0 = qt.Qobj(
        [
            [1.0, 0.0],
            [0.0, np.sqrt(1.0 - gamma)]
        ]
    )

    K1 = qt.Qobj(
        [
            [0.0, np.sqrt(gamma)],
            [0.0, 0.0]
        ]
    )

    return K0, K1


# ============================================================
# LOCAL AMPLITUDE DAMPING ON ONE SYSTEM QUBIT
# ============================================================

def apply_local_amplitude_damping(
    rho_state,
    target,
    total_qubits,
    gamma
):
    """
    Apply amplitude damping to one target qubit.

    Qubit ordering:

        [ancilla, replica-1 qubits, replica-2 qubits, ...]

    target=0 corresponds to the ancilla.
    Therefore system/replica qubits start from target=1.

    The ancilla is NOT damped in this experiment.
    """

    K0, K1 = amplitude_damping_kraus(gamma)

    operators_0 = []
    operators_1 = []

    for q in range(total_qubits):

        if q == target:

            operators_0.append(K0)
            operators_1.append(K1)

        else:

            operators_0.append(qt.qeye(2))
            operators_1.append(qt.qeye(2))

    K0_full = qt.tensor(operators_0)
    K1_full = qt.tensor(operators_1)

    return (
        K0_full * rho_state * K0_full.dag()
        +
        K1_full * rho_state * K1_full.dag()
    )


# ============================================================
# AMPLITUDE DAMPING ON ALL REPLICA/SYSTEM QUBITS
# ============================================================

def apply_system_amplitude_damping(
    rho_state,
    m,
    n,
    gamma
):
    """
    Apply amplitude damping independently to every system
    qubit in every replica.

    The ancilla is excluded.

    Total number of qubits:
        1 + m*n

    where the first qubit is the ancilla.
    """

    total_qubits = 1 + m * n

    # Ancilla = target 0
    # System qubits = targets 1,...,m*n

    for target in range(1, total_qubits):

        rho_state = apply_local_amplitude_damping(
            rho_state=rho_state,
            target=target,
            total_qubits=total_qubits,
            gamma=gamma
        )

    return rho_state


# ============================================================
# R-ZNE FOLDING CALCULATION
# ============================================================

def calculate_rzne_data(
    framework,
    gamma=0.02,
    max_c=4,
    shots=None
):
    """
    R-ZNE folding under amplitude damping on all replica/system
    qubits.

    Folding:

        U_c = U (U^\dagger U)^c

    with

        s_c = 2c + 1.

    Amplitude damping is applied after every U or U^\dagger
    block.

    The ancilla itself is NOT subjected to amplitude damping.
    """

    rho = framework.rho
    m = framework.m
    n = framework.n

    U = framework.CVm
    Udag = U.dag()

    # --------------------------------------------------------
    # Initial replicated state
    # --------------------------------------------------------

    rho_total = qt.tensor(
        framework.rho_anc,
        *[rho for _ in range(m)]
    )

    # --------------------------------------------------------
    # Final Hadamard on ancilla
    # --------------------------------------------------------

    Hanc = qt.tensor(
        framework.H,
        *[
            framework.I
            for _ in range(m * n)
        ]
    )

    # --------------------------------------------------------
    # Post-H measurement observable
    #
    # Measuring Z after H is equivalent to measuring X before H:
    #
    #       H X H = Z
    #
    # --------------------------------------------------------

    Zanc = qt.tensor(
        qt.sigmaz(),
        *[
            framework.I
            for _ in range(m * n)
        ]
    )

    # --------------------------------------------------------
    # Noise after U
    # --------------------------------------------------------

    def noisy_U(rho_state):

        rho_state = U * rho_state * Udag

        rho_state = apply_system_amplitude_damping(
            rho_state,
            m=m,
            n=n,
            gamma=gamma
        )

        return rho_state

    # --------------------------------------------------------
    # Noise after U^\dagger
    # --------------------------------------------------------

    def noisy_Udag(rho_state):

        rho_state = Udag * rho_state * U

        rho_state = apply_system_amplitude_damping(
            rho_state,
            m=m,
            n=n,
            gamma=gamma
        )

        return rho_state

    # --------------------------------------------------------
    # Folded circuit
    # --------------------------------------------------------

    def execute_folded_circuit(c):

        rho_state = rho_total.copy()

        # Initial U
        rho_state = noisy_U(rho_state)

        # Additional U^\dagger U pairs
        for _ in range(c):

            rho_state = noisy_Udag(rho_state)
            rho_state = noisy_U(rho_state)

        # Final Hadamard
        rho_state = (
            Hanc
            * rho_state
            * Hanc.dag()
        )

        return rho_state

    # --------------------------------------------------------
    # Exact replica invariant
    # --------------------------------------------------------

    R_exact = np.real(
        (rho ** m).tr()
    )

    # --------------------------------------------------------
    # Storage
    # --------------------------------------------------------

    scales = []
    values = []

    # --------------------------------------------------------
    # Folded simulations
    # --------------------------------------------------------

    for c in range(max_c + 1):

        s = 2 * c + 1

        rho_final = execute_folded_circuit(c)

        expectation = np.real(
            (Zanc * rho_final).tr()
        )

        # ----------------------------------------------------
        # Optional finite-shot sampling
        # ----------------------------------------------------

        if shots is not None:

            p0 = (1.0 + expectation) / 2.0
            p0 = np.clip(p0, 0.0, 1.0)

            samples = np.random.choice(
                [1.0, -1.0],
                size=shots,
                p=[p0, 1.0 - p0]
            )

            value = np.mean(samples)

        else:

            value = expectation

        scales.append(s)
        values.append(value)

    scales = np.asarray(scales, dtype=float)
    values = np.asarray(values, dtype=float)

    # ========================================================
    # LOG-LINEAR FIT
    # ========================================================

    if np.all(values > 0):

        log_values = np.log(values)

        fit = linregress(
            scales,
            log_values
        )

        slope = fit.slope
        intercept = fit.intercept

        alpha_eff = np.exp(slope)
        R_fit = np.exp(intercept)

        R2_fit = fit.rvalue ** 2

        log_fit = (
            intercept
            + slope * scales
        )

    else:

        slope = np.nan
        intercept = np.nan
        alpha_eff = np.nan
        R_fit = np.nan
        R2_fit = np.nan

        log_fit = np.full_like(
            scales,
            np.nan
        )

        log_values = np.full_like(
            scales,
            np.nan
        )

    # ========================================================
    # TWO-POINT R-ZNE
    #
    # If the signal were exactly
    #
    # R(s) = R alpha^s,
    #
    # then
    #
    # R = sqrt[R(1)^3 / R(3)].
    #
    # For amplitude damping this is NOT expected to be exact.
    # ========================================================

    R1 = values[0]
    R3 = values[1]

    if R1 > 0 and R3 > 0:

        R_RZNE = np.sqrt(
            R1 ** 3 / R3
        )

    else:

        R_RZNE = np.nan

    # ========================================================
    # ERRORS
    # ========================================================

    raw_error = abs(
        R1 - R_exact
    )

    rzne_error = abs(
        R_RZNE - R_exact
    )

    return {
        "scales": scales,
        "values": values,
        "log_values": log_values,
        "log_fit": log_fit,

        "exact": R_exact,

        "gamma": gamma,

        "alpha_eff": alpha_eff,
        "R_fit": R_fit,
        "R2_fit": R2_fit,

        "R1": R1,
        "R3": R3,
        "R_RZNE": R_RZNE,

        "raw_error": raw_error,
        "rzne_error": rzne_error,

        "m": m,
        "n": n,
        "shots": shots
    }


