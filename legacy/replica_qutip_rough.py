"""
Replica interference + Replica Zero-Noise Extrapolation (R-ZNE)

Protocol:

    rho^(⊗m) -> H_anc -> C(V_m) -> H_anc -> measure ancilla

The ideal expectation value is

    <Z_anc> = Tr(rho^m).

Replica ZNE uses unitary folding

    U_m^(c) = U_m (U_m^dagger U_m)^c

with scale

    s = 2c + 1.

For c = 0 and c = 1:

    R_m(0) = alpha R_m
    R_m(1) = alpha^3 R_m

and therefore

    R_m = sqrt( R_m(0)^3 / R_m(1) ).

No density-matrix reconstruction or tomography is performed.
"""


# ============================================================
# 1. Basic state utilities
# ============================================================

def validate_density_matrix(rho: np.ndarray, atol: float = 1e-10):
    """Check that rho is a valid density matrix."""

    rho = np.asarray(rho, dtype=complex)

    if rho.ndim != 2 or rho.shape[0] != rho.shape[1]:
        raise ValueError("rho must be a square matrix.")

    if not np.allclose(rho, rho.conj().T, atol=atol):
        raise ValueError("rho must be Hermitian.")

    if not np.isclose(np.trace(rho), 1.0, atol=atol):
        raise ValueError("rho must have trace 1.")

    eigenvalues = np.linalg.eigvalsh(rho)

    if np.min(eigenvalues) < -atol:
        raise ValueError("rho must be positive semidefinite.")


def trace_power(rho: np.ndarray, m: int) -> float:
    """Return R_m(rho) = Tr(rho^m)."""

    if m < 1:
        raise ValueError("m must be >= 1.")

    value = np.trace(np.linalg.matrix_power(rho, m))

    return float(np.real_if_close(value))


# ============================================================
# 2. Controlled cyclic permutation
# ============================================================

def controlled_cyclic_permutation(
    qc: QuantumCircuit,
    anc: int,
    replica_qubits: list[list[int]],
):
    """
    Apply the controlled cyclic permutation C(V_m).

    Convention:

        V_m |psi_0>|psi_1>...|psi_{m-1}>
        =
        |psi_{m-1}>|psi_0>...|psi_{m-2}>.

    A right cyclic shift can be constructed from adjacent swaps:

        SWAP(m-2,m-1)
        SWAP(m-3,m-2)
        ...
        SWAP(0,1)

    Every SWAP is controlled by the ancilla.
    """

    m = len(replica_qubits)

    if m < 2:
        return

    n = len(replica_qubits[0])

    for replica in replica_qubits:
        if len(replica) != n:
            raise ValueError(
                "All replicas must contain the same number of qubits."
            )

    # Right cyclic shift
    for r in range(m - 2, -1, -1):

        for q in range(n):

            qc.cswap(
                anc,
                replica_qubits[r][q],
                replica_qubits[r + 1][q],
            )


# ============================================================
# 3. Build U_m = C(V_m)
# ============================================================

def build_replica_unitary(
    m: int,
    n_system_qubits: int,
    anc: int = 0,
) -> QuantumCircuit:
    """
    Construct the controlled cyclic permutation block

        U_m = C(V_m).
    """

    total_qubits = 1 + m * n_system_qubits

    qc = QuantumCircuit(
        total_qubits,
        name=f"C_V_m_{m}",
    )

    replica_qubits = []

    for r in range(m):

        start = 1 + r * n_system_qubits

        replica_qubits.append(
            list(
                range(
                    start,
                    start + n_system_qubits
                )
            )
        )

    controlled_cyclic_permutation(
        qc,
        anc,
        replica_qubits,
    )

    return qc


# ============================================================
# 4. Full replica-interference circuit
# ============================================================

def build_interference_circuit(
    rho: np.ndarray,
    m: int,
    folding_c: int = 0,
) -> QuantumCircuit:

    """
    Construct

        rho^(⊗m)
           |
           H
           |
        U_m^(c)
           |
           H
           |
         Z_anc

    where

        U_m^(c)
        =
        U_m (U_m^dagger U_m)^c.
    """

    validate_density_matrix(rho)

    dim = rho.shape[0]

    # Number of system qubits
    n = int(round(math.log2(dim)))

    if 2**n != dim:
        raise ValueError(
            "Dimension of rho must be 2^n."
        )

    if m < 2:
        raise ValueError(
            "This implementation requires m >= 2."
        )

    if folding_c < 0:
        raise ValueError(
            "folding_c must be >= 0."
        )

    total_qubits = 1 + m * n

    q = QuantumRegister(
        total_qubits,
        "q"
    )

    c = ClassicalRegister(
        1,
        "c"
    )

    qc = QuantumCircuit(q, c)

    anc = 0

    # --------------------------------------------------------
    # Construct rho^(tensor m)
    # --------------------------------------------------------

    rho_rep = rho.copy()

    for _ in range(m - 1):
        rho_rep = np.kron(
            rho_rep,
            rho
        )

    # Ancilla initially |0><0|
    ancilla_zero = np.array(
        [
            [1.0, 0.0],
            [0.0, 0.0],
        ],
        dtype=complex
    )

    full_rho = np.kron(
        ancilla_zero,
        rho_rep
    )

    # Directly initialize simulator to rho^(tensor m)
    qc.set_density_matrix(
        DensityMatrix(full_rho)
    )

    # --------------------------------------------------------
    # Prepare ancilla |+>
    # --------------------------------------------------------

    qc.h(anc)

    # --------------------------------------------------------
    # Construct U_m = C(V_m)
    # --------------------------------------------------------

    U = build_replica_unitary(
        m=m,
        n_system_qubits=n,
        anc=anc,
    )

    # --------------------------------------------------------
    # Unit folding
    #
    # U_m^(c) = U_m (U_m^dagger U_m)^c
    #
    # --------------------------------------------------------

    for _ in range(folding_c):

        qc.compose(
            U.inverse(),
            qubits=list(range(total_qubits)),
            inplace=True,
        )

        qc.compose(
            U,
            qubits=list(range(total_qubits)),
            inplace=True,
        )

    # Final U
    qc.compose(
        U,
        qubits=list(range(total_qubits)),
        inplace=True,
    )

    # --------------------------------------------------------
    # Measure X_anc
    #
    # Applying H first means computational Z measurement
    # corresponds to measuring X before the final H.
    # --------------------------------------------------------

    qc.h(anc)

    qc.measure(
        anc,
        c[0]
    )

    return qc


